const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const files = {
  site: path.join(root, 'data', 'site.json'),
  attacks: path.join(root, 'data', 'attacks.json'),
  games: path.join(root, 'data', 'games.json')
};

const data = {};
for (const [key, file] of Object.entries(files)) {
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  data[key] = key === 'attacks' ? parsed.attacks : parsed;
}

const out = path.join(root, 'assets', 'data-inline.js');
const contents = `/* Generated by tools/build-inline-data.js — do not edit by hand. */\nwindow.CSA_DATA = ${JSON.stringify(data, null, 2)};\n`;
fs.writeFileSync(out, contents, 'utf8');
process.stdout.write(`Wrote ${out} (${(contents.length / 1024).toFixed(1)} KB)\n`);
